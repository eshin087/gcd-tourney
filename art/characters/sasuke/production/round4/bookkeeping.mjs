import fs from 'node:fs';
const versions={superDash:7,jumpSquat:5,beamFire:6,dash:6};
let s=fs.readFileSync('art/manifest.json','utf8');
const start=s.indexOf('"sasuke": {'),end=s.indexOf('"killua": {',start);
let own=s.slice(start,end);
for(const [name,v] of Object.entries(versions)) own=own.replace(new RegExp('("'+name+'": \\{[^\\n]*?"version": )\\d+'), '$1'+v);
fs.writeFileSync('art/manifest.json',s.slice(0,start)+own+s.slice(end));
s=fs.readFileSync('art/REVIEW.md','utf8');
const sep='|---|---|---|---|---|---|---|---|';
const rows=Object.entries(versions).map(([a,v])=>`| 2026-10-12 | sasuke | ${a} | [raw](characters/sasuke/raw/${a}_v${String(v).padStart(2,'0')}.png) | v${String(v).padStart(2,'0')} | needs review | Round4 selected redraw; preserve approvedVersion and earlier immutable candidates. | Anatomical audit and strict pack pending; no full-body pass. [Inventory](characters/sasuke/production/round4/candidate-inventory.json). |`).join('\n');
fs.writeFileSync('art/REVIEW.md',s.replace(sep,sep+'\n'+rows));
s=fs.readFileSync('art/TRACKER.md','utf8');
const i=s.indexOf('## Sasuke'),j=s.indexOf('## Killua',i); let t=s.slice(i,j);
for(const [a,v] of Object.entries(versions))t=t.replace(new RegExp('(\\| '+a+' \\|[^\\n]*?approved \\| )v\\d+'), '$1v'+String(v).padStart(2,'0'));
fs.writeFileSync('art/TRACKER.md',s.slice(0,i)+t+s.slice(j));
s=fs.readFileSync('CHANGELOG.md','utf8').replace('## [Unreleased]','## [Unreleased]\n\n- Sasuke round4: measured sandal failures trigger beamFire/dash redraws; superDash and spot-dodge candidates filed for full-body audit. No art approval or runtime calibration change.'); fs.writeFileSync('CHANGELOG.md',s);
