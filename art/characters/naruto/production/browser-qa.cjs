const { chromium } = require('C:/Users/eshin/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('node:fs');
const base='art/characters/naruto/production/';
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const messages=[],errors=[],httpErrors=[];
 page.on('console',m=>messages.push(m.text()));
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)httpErrors.push({url:r.url(),status:r.status()});});
 await page.goto('http://127.0.0.1:5188/?fight=naruto,naruto&mode=solo&art=custom&debug');
 await page.waitForFunction(()=>typeof window.freezeCpu==='function',null,{timeout:30000});
 await page.evaluate(async()=>{await window.waitFight();window.freezeCpu();window.step(1);window.snap();});
 await page.screenshot({path:base+'game-preview.png'});
 await page.evaluate(()=>{window.unsnap();window.press('KeyJ',8);window.snap();});
 await page.screenshot({path:base+'game-attack.png'});
 const custom=messages.filter(s=>s.includes('using custom sheet for naruto'));
 if(!custom.length)throw Error('Custom Naruto sheet not loaded');
 await page.goto('http://127.0.0.1:5188/art-review/naruto/final/index.html');
 await page.waitForFunction(()=>window.reviewReady===true);
 const names=await page.locator('#animation option').evaluateAll(es=>es.map(e=>e.value));
 if(names.length!==42)throw Error('Expected 42 animation choices');
 for(const n of names){await page.selectOption('#animation',n);await page.click('#step');}
 await page.selectOption('#animation','special');
 await page.check('#boxes');
 await page.screenshot({path:base+'review-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.selectOption('#animation','run');
 await page.uncheck('#boxes');
 await page.click('#play');
 await page.waitForTimeout(450);
 await page.click('#play');
 await page.screenshot({path:base+'review-mobile.png',fullPage:true});
 const mobile=await page.evaluate(()=>({width:innerWidth,documentWidth:document.documentElement.scrollWidth,images:[...document.querySelectorAll('img')].map(i=>({src:i.getAttribute('src'),ok:i.complete&&i.naturalWidth>0}))}));
 const allowedErrors=httpErrors.filter(e=>!e.url.endsWith('/favicon.ico')&&!e.url.endsWith('/QA.md')&&!e.url.includes('game-preview'));
 const result={custom,animationsExercised:names.length,errors,httpErrors,mobile};
 fs.writeFileSync(base+'qa-browser.json',JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result));
 await browser.close();
 if(errors.length||allowedErrors.length||mobile.documentWidth>mobile.width||mobile.images.some(i=>!i.ok&&!i.src.includes('game-preview')))throw Error('Browser QA failed');
})().catch(e=>{console.error(e);process.exit(1);});
