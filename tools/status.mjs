#!/usr/bin/env node
// npm run status [-- --write]
// One screen of "where are we" for the user, who switches between Claude and Codex on a phone:
// what needs them now (the approvals desk's open asks, ADR 0039), REVIEW.md rows still marked for review,
// each fighter's art progress (art/manifest.json), what Claude and Codex are working on (docs/TASKS.md) and
// the last commits. --write also refreshes the generated block of docs/NOW.md. Read-only apart from that and
// the relay's own ask files; Node built-ins only.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { DESK_TITLE, deskAlive, openAsks } from './relay.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => { try { return fs.readFileSync(path.join(root, p), 'utf8'); } catch { return ''; } };
const cells = (line) => line.split('|').slice(1, -1).map((c) => c.trim());
const strip = (s) => s.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1').replace(/[*`]/g, '');
const clip = (s, n) => (s.length > n ? s.slice(0, n - 1) + '…' : s);

// ---- REVIEW.md rows still marked for review: only each asset's newest row counts (rows are newest first), so a
// version replaced by a later one is not listed again
function reviewQueue() {
  const rows = read('art/REVIEW.md').split(/\r?\n/).filter((l) => l.startsWith('| 20')).map(cells);
  const newest = new Map();
  for (const c of rows) {
    const key = `${c[1].toLowerCase()}|${strip(c[2]).toLowerCase()}`;
    if (!newest.has(key)) newest.set(key, c);
  }
  return [...newest.values()].filter((c) => /needs review/i.test(c[5] || '')).map((c) => ({
    date: c[0], who: c[1], asset: strip(c[2]), version: c[4], file: (c[3].match(/\(([^)]+)\)/) || [])[1] || '',
  }));
}

// ---- what the approvals desk would ask the user now (fails soft: status must work without .relay/)
function deskAsks() {
  try { return { open: openAsks(), on: Boolean(deskAlive()) }; } catch { return { open: [], on: false }; }
}

// ---- per-fighter art progress from the manifest
function fighters() {
  let m;
  try { m = JSON.parse(read('art/manifest.json')); } catch { return []; }
  const core = new Set(m.coreAnimations || []);
  return Object.entries(m.characters || {}).map(([id, c]) => {
    const anims = Object.entries(c.animations || {});
    const coreAnims = anims.filter(([n]) => core.has(n));
    const approved = (list) => list.filter(([, a]) => a.approvedVersion).length;
    const refs = Object.entries(c.reference || {});
    const assets = [
      ...refs.map(([n, a]) => ({ name: n, ...a })),
      ...anims.map(([n, a]) => ({ name: n, ...a })),
      ...Object.entries(c.ui || {}).map(([n, a]) => ({ name: 'ui.' + n, ...a })),
    ].sort((a, b) => (a.step ?? 99) - (b.step ?? 99));
    const next = assets.find((a) => !a.approvedVersion);
    return {
      id,
      refs: `${refs.filter(([, a]) => a.approvedVersion).length}/${refs.length}`,
      core: `${approved(coreAnims)}/${coreAnims.length}`,
      all: `${approved(anims)}/${anims.length}`,
      next: next ? `${next.name} (step ${next.step}, ${next.status}${next.version ? ` v${String(next.version).padStart(2, '0')}` : ''})` : 'all approved',
    };
  });
}

// ---- task board rows by owner
function tasks() {
  const rows = read('docs/TASKS.md').split(/\r?\n/).filter((l) => /^\| [A-Z]+[A-Z0-9-]*\s*\|/.test(l)).map(cells);
  const pick = (owner, states) => rows.filter((c) => c[2] === owner && states.includes(c[3])).map((c) => `${c[0]}: ${clip(strip(c[1]), 90)} [${c[3]}]`);
  return {
    claude: pick('Claude', ['in-progress', 'blocked']),
    codex: pick('Codex', ['in-progress', 'blocked']),
    review: rows.filter((c) => c[3] === 'review').map((c) => `${c[0]} (${c[2]})`),
    user: rows.filter((c) => c[2] === 'User' && !['done'].includes(c[3])).map((c) => `${c[0]}: ${clip(strip(c[1]), 90)} [${c[3]}]`),
  };
}

function commits() {
  try {
    return execFileSync('git', ['log', '--format=%h %ad %s', '--date=format:%m-%d %H:%M', '-6'], { cwd: root, encoding: 'utf8' }).trim().split('\n');
  } catch {
    return ['(git log unavailable)'];
  }
}

function render() {
  const L = [];
  const now = new Date();
  L.push(`_Generated by \`npm run status\` at ${now.toISOString().slice(0, 16).replace('T', ' ')} UTC._`);
  L.push('');
  const desk = deskAsks();
  L.push(`### Needs you now (${desk.open.length})`);
  L.push(`_Answered only in the Claude chat "${DESK_TITLE}" (ADR 0039); its watcher is ${desk.on ? 'on' : 'off: open that chat and type /desk'}._`);
  if (!desk.open.length) L.push('- nothing');
  for (const a of desk.open) {
    const from = a.source === 'codex' ? `Codex lane ${a.lane}` : `Claude chat "${a.from}"`;
    L.push(`- **${a.kind}** from ${from}: ${clip(a.note, 220)}${a.link ? ` ${a.link}` : ''}`);
  }
  L.push('');
  const q = reviewQueue();
  L.push(`### Still marked "needs review" in art/REVIEW.md (${q.length})`);
  L.push('_Bookkeeping: the newest row of each asset. Anything the user must actually answer is in "Needs you now"._');
  if (!q.length) L.push('- nothing');
  // grouped per character/area so a phone screen stays readable; newest first
  const groups = new Map();
  for (const r of q) { if (!groups.has(r.who)) groups.set(r.who, []); groups.get(r.who).push(r); }
  for (const [who, list] of groups) {
    const shown = list.slice(0, 4).map((r) => `${r.asset} ${r.version}`).join(', ');
    L.push(`- **${who}** (${list.length}): ${shown}${list.length > 4 ? ', …' : ''}`);
  }
  L.push('');
  L.push('### Fighter art (approved)');
  L.push('');
  L.push('| fighter | references | core anims | all anims | next asset |');
  L.push('|---|---|---|---|---|');
  for (const f of fighters()) L.push(`| ${f.id} | ${f.refs} | ${f.core} | ${f.all} | ${f.next} |`);
  L.push('');
  const t = tasks();
  L.push('### Claude is on');
  L.push(...(t.claude.length ? t.claude.map((x) => `- ${x}`) : ['- nothing in progress']));
  L.push('');
  L.push('### Codex is on');
  L.push(...(t.codex.length ? t.codex.map((x) => `- ${x}`) : ['- nothing in progress']));
  if (t.review.length) {
    L.push('');
    L.push(`### Finished, waiting for a check (${t.review.length})`);
    L.push(`- ${t.review.join(', ')}`);
  }
  if (t.user.length) {
    L.push('');
    L.push('### Open user decisions');
    L.push(...t.user.map((x) => `- ${x}`));
  }
  L.push('');
  L.push('### Last commits');
  L.push(...commits().map((x) => `- ${x}`));
  return L.join('\n');
}

const out = render();
if (process.argv.includes('--write')) {
  const p = path.join(root, 'docs', 'NOW.md');
  const s = fs.readFileSync(p, 'utf8');
  const a = s.indexOf('<!-- status:begin -->'), b = s.indexOf('<!-- status:end -->');
  if (a < 0 || b < a) {
    console.error('[status] docs/NOW.md has no <!-- status:begin --> / <!-- status:end --> markers');
    process.exit(1);
  }
  fs.writeFileSync(p, s.slice(0, a) + '<!-- status:begin -->\n' + out + '\n' + s.slice(b));
  console.log('[status] docs/NOW.md updated');
}
console.log(out);
