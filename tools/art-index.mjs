#!/usr/bin/env node
// Writes public/art-index.json: the list of optional art files that exist under public/
// (packed sheets, portraits, atlases, stage and NPC art). Runs automatically before every
// `npm run build` (prebuild). The game reads it in production so it never requests a missing
// file (see src/core/artIndex.js).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PUBLIC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');
const files = [];
// byte size of every file of 32 kB or more: the loading screen weighs its progress bar by them (ENG-102); smaller
// files are left out to keep the index small and count as 16 kB, and so are the review pages' images (art-review/,
// calibration folders), which the game never loads
const bytes = {};
const GAME_ART = /^(characters\/[^/]+|npc\/[^/]+|vfx|crowd|stage|ui|decals)\/[^/]+\.png$/;
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(png|json)$/i.test(e.name) && e.name !== 'art-index.json') {
      const rel = path.relative(PUBLIC, p).split(path.sep).join('/');
      files.push(rel);
      const size = fs.statSync(p).size;
      if (size >= 32768 && GAME_ART.test(rel)) bytes[rel] = size;
    }
  }
};
if (fs.existsSync(PUBLIC)) walk(PUBLIC);
files.sort();
fs.mkdirSync(PUBLIC, { recursive: true });
fs.writeFileSync(path.join(PUBLIC, 'art-index.json'), JSON.stringify({ note: 'generated by tools/art-index.mjs; do not edit', files, bytes }, null, 1) + '\n');
console.log(`art-index: ${files.length} file(s)`);
