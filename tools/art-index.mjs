#!/usr/bin/env node
// Writes public/art-index.json: the list of optional art files that exist under public/
// (packed sheets, portraits, atlases, stage and NPC art). Runs automatically before every
// `npm run build` (prebuild). The game reads it in production so it never requests a missing
// file (see src/core/artIndex.js).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PUBLIC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');
const files = [];
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(png|json)$/i.test(e.name) && e.name !== 'art-index.json') files.push(path.relative(PUBLIC, p).split(path.sep).join('/'));
  }
};
if (fs.existsSync(PUBLIC)) walk(PUBLIC);
files.sort();
fs.mkdirSync(PUBLIC, { recursive: true });
fs.writeFileSync(path.join(PUBLIC, 'art-index.json'), JSON.stringify({ note: 'generated by tools/art-index.mjs; do not edit', files }, null, 1) + '\n');
console.log(`art-index: ${files.length} file(s)`);
